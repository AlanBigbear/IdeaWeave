_TEMPLATE_BY_KEY = {item["key"]: item for item in PRESET_SKILL_TEMPLATES}


def list_preset_templates() -> list[dict]:
    zone_label_by_key = {item["key"]: item["label"] for item in PERSONA_OPTIONS["zones"]}
    return [
        {
            "key": item["key"],
            "zone_key": item["zone_key"],
            "zone_label": zone_label_by_key.get(item["zone_key"], ""),
            "name": item["name"],
            "desc": item["desc"],
        }
        for item in PRESET_SKILL_TEMPLATES
    ]


def build_preset_skill_from_template(persona, template_key: str) -> dict | None:
    """以命名模板为骨架、用户选择为个性化参数，组合一份 Skill。"""
    template = _TEMPLATE_BY_KEY.get(template_key)
    if template is None:
        return None
    skill = build_preset_skill(persona)
    old_positioning = skill["positioning"]
    skill["hook_formula"] = [template["hook"], *skill["hook_formula"][1:]]
    skill["tone_rules"] = [template["catchphrase"], *skill["tone_rules"]][:4]
    skill["positioning"] = template["positioning"]
    skill["system_prompt"] = skill["system_prompt"].replace(old_positioning, template["positioning"])
    skill["template_key"] = template["key"]
    return skill
