def _zone_key(persona) -> str:
    zone = (getattr(persona, "zone", "") or "").strip()
    return _ZONE_LABEL_TO_KEY.get(zone, "")


def _first_style_key(persona) -> str:
    content = (getattr(persona, "content_style", "") or "").strip()
    # 优先长词匹配（如「线下体验 / 探店」先于「探店实测」不被截断误配）
    for label in sorted(_STRUCTURE_BY_STYLE, key=len, reverse=True):
        if label in content:
            return label
    return ""


def _freq_line(persona) -> str:
    freq = (getattr(persona, "update_freq", "") or "").strip()
    for label, key in _FREQ_LABEL_TO_KEY.items():
        if label in freq:
            return _FREQ_LINE[key]
    return _FREQ_FALLBACK_LINE


def _comment_line(persona) -> str:
    comment = (getattr(persona, "comment_style", "") or "").strip()
    for label, key in _COMMENT_LABEL_TO_KEY.items():
        if label in comment:
            return _COMMENT_LINE[key]
    return _COMMENT_FALLBACK_LINE


def build_preset_skill(persona) -> dict:
    """根据人设选择组合出一份确定性 Skill（brief 结构与 AI 编译版一致）。"""
    zone = _ZONE_SKILL.get(_zone_key(persona)) or _ZONE_FALLBACK
    structure = _STRUCTURE_BY_STYLE.get(_first_style_key(persona), _STRUCTURE_FALLBACK)
    freq = _freq_line(persona)
    comment = _comment_line(persona)
    name = persona.name or "这位 UP 主"
    audience = persona.audience or "目标观众"

    system_prompt = (
        f"你是为 UP 主「{name}」工作的虚拟编导。频道定位：{zone['positioning']}，主要给{audience}看。"
        f"选题口味：{'；'.join(zone['topics'])}。{freq}。"
        f"语言风格：{'；'.join(zone['tone'])}。"
        f"脚本结构：{structure}。"
        f"互动方式：{comment}。"
        f"内容红线：{'；'.join(zone['red'])}。"
        "所有产出必须贴合这个人设，换一个分区或风格就不该适用。"
    )

    return {
        "positioning": zone["positioning"],
        "hook_formula": zone["hooks"],
        "tone_rules": zone["tone"][:4],
        "topic_preferences": [*zone["topics"], freq][:4],
        "script_structure": structure,
        "interaction_style": comment,
        "red_lines": zone["red"],
        "system_prompt": system_prompt,
    }


